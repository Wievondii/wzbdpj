#include "alarm.h"
#include "delay.h"

/************************************************************
 * 功能: 报警系统初始化
 * 说明: GPIO在gpio.c中已初始化，此处仅做初始状态设置
 ************************************************************/
void Alarm_Init(void)
{
    BUZZER_OFF();
    LED_ALARM_OFF();
}

/************************************************************
 * 功能: 开启报警
 ************************************************************/
void Alarm_On(void)
{
    BUZZER_ON();
    LED_ALARM_ON();
}

/************************************************************
 * 功能: 关闭报警
 ************************************************************/
void Alarm_Off(void)
{
    BUZZER_OFF();
    LED_ALARM_OFF();
}

/************************************************************
 * 功能: 短促蜂鸣提示音
 ************************************************************/
void Alarm_Beep_Short(void)
{
    BUZZER_ON();
    Delay_ms(100);
    BUZZER_OFF();
}

/************************************************************
 * 功能: 车位已满报警 (三次短促鸣叫)
 ************************************************************/
void Alarm_Full_Warning(void)
{
    uint8_t i;
    for(i = 0; i < 3; i++)
    {
        BUZZER_ON();
        LED_ALARM_ON();
        Delay_ms(200);
        BUZZER_OFF();
        LED_ALARM_OFF();
        Delay_ms(150);
    }
}
